#!/usr/bin/env python3
"""Generate bit-exact C++ factory tables from the statically recovered JSON.

The input retains raw name storage and float words. This generator verifies that
those words agree with the decimal values and reproduce the recovered bank hash.
It does not execute the legacy plug-in or infer parameter behavior.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct


ROOT = Path(__file__).resolve().parents[1]
EXPECTED_BINARY_SHA256 = "aee3175bd128a69ee82c8e31a34a36284e21698f022c6f722a6c42f2fc94b635"
EXPECTED_BANK_SHA256 = "763f91576c68a2f15f66db2c41a66644fd1d5e3ab42cf42ebd45ef01df3791f1"


def generate(factory_path, parameter_path):
    factory = json.loads(factory_path.read_text())
    parameters = json.loads(parameter_path.read_text())
    if factory.get("program_count") != 128 or factory.get("parameter_count") != 38:
        raise ValueError("Expected 128 programs and 38 parameters")
    if factory["provenance"]["source_sha256"] != EXPECTED_BINARY_SHA256:
        raise ValueError("Factory source binary digest differs")
    if parameters["provenance"]["source_sha256"] != EXPECTED_BINARY_SHA256:
        raise ValueError("Parameter source binary digest differs")
    if len(factory["programs"]) != 128 or len(parameters["parameters"]) != 38:
        raise ValueError("Factory or parameter table length differs")
    bank = bytearray()
    names, words = [], []
    for index, program in enumerate(factory["programs"]):
        if program["index"] != index:
            raise ValueError("Program indices are not contiguous")
        name = bytes.fromhex(program["name_storage_hex"])
        bits = [int(word, 16) for word in program["float32_bits_hex"]]
        if len(name) != 32 or len(bits) != 38 or any(b > 127 for b in name):
            raise ValueError("Unexpected factory record layout")
        raw = struct.pack("<38I", *bits)
        if struct.pack("<38f", *program["values"]) != raw:
            raise ValueError("Decimal values differ from recorded float bits")
        bank += name + raw
        names.append("    {{ " + ", ".join(str(b) for b in name) + " }}")
        words.append("    {{ " + ", ".join(f"0x{word:08x}u" for word in bits) + " }}")
    if hashlib.sha256(bank).hexdigest() != EXPECTED_BANK_SHA256:
        raise ValueError("Reconstructed factory bank digest differs")
    parameter_names = []
    for index, parameter in enumerate(parameters["parameters"]):
        if parameter["index"] != index:
            raise ValueError("Parameter indices are not contiguous")
        parameter_names.append(json.dumps(parameter["name"]))
    return "\n".join([
        "// Generated by scripts/generate_factory_header.py. Do not edit by hand.",
        "// Source: analysis/recovered/factory-presets.json and parameter-map.json",
        f"// Original i386 binary SHA-256: {EXPECTED_BINARY_SHA256}",
        f"// Original factory bank SHA-256: {EXPECTED_BANK_SHA256}",
        "// Integer words retain the exact recovered IEEE-754 binary32 encodings.",
        "#pragma once", "", "#include <array>", "#include <cstdint>", "",
        "namespace plasticz::detail {", "",
        "inline constexpr std::array<std::array<char, 32>, 128> factoryProgramNames {{",
        ",\n".join(names), "}};", "",
        "inline constexpr std::array<std::array<std::uint32_t, 38>, 128> factoryParameterWords {{",
        ",\n".join(words), "}};", "",
        "inline constexpr std::array<const char*, 38> factoryParameterNames {{",
        "    " + ", ".join(parameter_names), "}};", "",
        "} // namespace plasticz::detail", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--factory", type=Path, default=ROOT / "analysis/recovered/factory-presets.json")
    parser.add_argument("--parameters", type=Path, default=ROOT / "analysis/recovered/parameter-map.json")
    parser.add_argument("--output", type=Path, default=ROOT / "src/FactoryPresets.h")
    args = parser.parse_args()
    result = generate(args.factory, args.parameters)
    args.output.write_text(result)
    print(f"Generated {args.output}; all 4,864 float words and 4,096 name bytes verified")


if __name__ == "__main__":
    main()
